import assert from "node:assert/strict";
import { chromium, expect } from "@playwright/test";
import * as XLSX from "xlsx";
import { mkdir, readFile } from "node:fs/promises";

// Called only with verify-rbac's isolated test database and authenticated client.
export async function verifyShareholderBallots({ db, admin, origin, check }) {
  const shares = { "card-a": 120.25, "card-b": 70.5, "card-own": 50, "card-ext-a": 30,
    "card-ext-b": 20, "card-late": 15, "card-concurrent": 10, "card-zero": 0, "card-absent": 5 };
  for (const [id, shareValue] of Object.entries(shares)) await admin.call("/api/shareholders", "POST",
    { id, name: `${id} shareholder`, nameAm: id, phone: "", address: "", shareValue: String(shareValue) }, 201);
  const meeting = (await admin.call("/api/meetings", "POST", { title: "Independent shareholder cards", date: "2026-11-11T09:00:00Z", location: "Test Hall", quorum: 1, winnerCount: 1 }, 201)).item;
  const prefix = `/api/meetings/${meeting.id}`;
  const nominees = [];
  for (const shareholderId of ["card-own", "card-a", "card-b"]) nominees.push((await admin.call(`${prefix}/nominees`, "POST", { shareholderId, type: "standard" }, 201)).nominee);
  const choices = nominees.map((nominee) => nominee.id);
  await admin.call(`${prefix}/open`, "POST");
  await admin.call(`${prefix}/attendance`, "POST", { shareholderIds: ["card-a"], representativeShareholderId: "card-own" });
  const rep = await db.representative.findFirstOrThrow({ where: { shareholderId: "card-own" } });
  await admin.call(`${prefix}/attendance`, "POST", { shareholderIds: ["card-ext-a", "card-ext-b"], representativeId: "card-external", representativeName: "External delegate" });
  await admin.call(`${prefix}/attendance`, "POST", { shareholderIds: ["card-concurrent", "card-zero"] });
  await admin.call(`${prefix}/votingopen`, "POST");
  const post = (voterId, nomineeIds, expected = 200) => admin.call(`${prefix}/votes`, "POST", { voterId, nomineeIds }, expected);
  const lookup = (voterId) => admin.call(`${prefix}/votes?voterId=${encodeURIComponent(voterId)}`);
  const reverse = (voterId, nomineeIds, expected = 200) => admin.call(`${prefix}/votes`, "DELETE", { voterId, nomineeIds, reason: "Independent card verification correction" }, expected);
  for (const voterId of [rep.id, "card-external", "card-own", "card-absent"]) await post(voterId, [choices[0]], 403);
  await post("card-zero", [choices[0]], 400);
  await post("card-a", [choices[0]]);
  await admin.call("/api/shareholders/card-a", "PUT", { name: "Registry name changed", nameAm: "card-a", phone: "", address: "", shareValue: "999" });
  const aAttendance = await admin.call(`${prefix}/attendance?voterId=card-a`);
  assert.equal(aAttendance.attendance.length, 1);
  assert.equal(aAttendance.attendance[0].shareholderName, "card-a shareholder");
  assert.equal(Number(aAttendance.attendance[0].shareValue), shares["card-a"]);
  assert.equal(aAttendance.attendance[0].representedById, rep.id);
  await post("card-a", [choices[0]]);
  await post("card-a", [choices[1]], 400);
  await admin.call(`${prefix}/attendance`, "POST", { shareholderIds: ["card-own"] });
  await post("card-own", [choices[2]]);
  await admin.call(`${prefix}/attendance`, "POST", { shareholderIds: ["card-b"], representativeId: rep.id });
  assert.equal((await lookup("card-b")).voted.length, 0);
  await post("card-b", [choices[1]]);
  await post("card-ext-a", [choices[1]]);
  await post("card-ext-b", [choices[2]]);
  await admin.call(`${prefix}/attendance`, "POST", { shareholderIds: ["card-late"], representativeId: rep.id });
  const late = await db.attendance.findFirstOrThrow({ where: { meetingId: meeting.id, shareholderId: "card-late" } });
  await admin.call(`${prefix}/attendance/${late.id}`, "DELETE");
  const recorded = await db.vote.findMany({ where: { meetingId: meeting.id } });
  assert.equal(recorded.length, 5);
  for (const vote of recorded) {
    assert.equal(vote.weight, shares[vote.voterId]);
    assert.equal(Number(vote.snapshotVoterShareValue), shares[vote.voterId]);
    assert.equal(vote.snapshotVoterName, `${vote.voterId} shareholder`);
  }
  check("two represented cards choose different nominees; representative owns a third independent card; external delegates have no personal card; attendance snapshots remain fixed");

  const race = await Promise.all([choices[0], choices[1]].map((choice) => post("card-concurrent", [choice]).then(() => 200).catch((error) => { if (error.actual === 400) return 400; throw error; })));
  assert.deepEqual(race.sort(), [200, 400]);
  const concurrentChoice = (await lookup("card-concurrent")).voted[0];
  await Promise.all(Array.from({ length: 3 }, () => post("card-concurrent", [concurrentChoice])));
  assert.equal(await db.vote.count({ where: { meetingId: meeting.id, voterId: "card-concurrent" } }), 1);
  assert.equal((await reverse(rep.id, choices)).reversedCount, 0);
  assert.equal((await lookup("card-own")).voted.length, 1);
  const a = await db.attendance.findFirstOrThrow({ where: { meetingId: meeting.id, shareholderId: "card-a" } });
  await admin.call(`${prefix}/attendance/${a.id}`, "DELETE", undefined, 409);
  await reverse("card-a", [choices[0]]);
  await reverse("card-a", [choices[0]]);
  await admin.call(`${prefix}/attendance/${a.id}`, "DELETE");
  assert.equal((await lookup("card-own")).voted.length, 1);
  assert.equal((await lookup("card-b")).voted.length, 1);
  await admin.call(`${prefix}/attendance`, "POST", { shareholderIds: ["card-a"], representativeId: rep.id });
  await post("card-a", [choices[0]]);
  assert.equal((await lookup("card-a")).voterWeight, 999);
  check("cumulative per-card limits survive concurrent submissions and retries; reversals and attendance removal affect only their shareholder");

  const report = await admin.call(`${prefix}/reports/voting?voterKind=represented`);
  assert.deepEqual(new Set(report.rows.map((row) => row.voterId)), new Set(["card-a", "card-b", "card-ext-a", "card-ext-b"]));
  assert.ok(report.rows.every((row) => row.voterKind === "represented" && row.representedById && !row.legacyCombined));
  const direct = await admin.call(`${prefix}/reports/voting?voterKind=direct`);
  assert.deepEqual(new Set(direct.rows.map((row) => row.voterId)), new Set(["card-own", "card-concurrent"]));
  const byRep = await admin.call(`${prefix}/reports/voting?search=${encodeURIComponent(rep.id)}`);
  assert.deepEqual(new Set(byRep.rows.map((row) => row.voterId)), new Set(["card-a", "card-b"]));
  const byExternalName = await admin.call(`${prefix}/reports/voting?search=External%20delegate`);
  assert.deepEqual(new Set(byExternalName.rows.map((row) => row.voterId)), new Set(["card-ext-a", "card-ext-b"]));
  const publicResults = await fetch(`${origin}/api/public/meetings/${meeting.id}/results`).then((response) => response.json());
  assert.equal(publicResults.ballotsCast, 6);
  assert.equal(publicResults.attendeesCount, 7);
  assert.equal(publicResults.totalSharesAttended, 999 + 70.5 + 50 + 30 + 20 + 10);
  assert.equal(publicResults.results.reduce((total, row) => total + row.totalWeight, 0), publicResults.totalSharesAttended);
  check("represented/direct report filters, searches by delegate ID/name and public totals count independent shareholder ballots");

  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(60000);
  const [cookieName, ...cookieValue] = admin.cookie.split("=");
  await context.addCookies([{ name: cookieName, value: cookieValue.join("="), url: origin }]);
  await mkdir(".local/shareholder-ballot-verification", { recursive: true });
  const enter = async (id) => {
    await page.getByLabel("Shareholder ID on voting card", { exact: true }).fill(id);
    await expect(page.getByRole("status").filter({ hasText: "choices used" })).toContainText(`${shares[id] ?? 999} shares`);
  };
  try {
    await page.goto(`${origin}/meetings/${meeting.id}/vote`);
    await enter("card-b");
    await expect(page.getByRole("status").filter({ hasText: "choices used" })).toContainText("Represented by card-own shareholder");
    await expect(page.getByRole("checkbox", { name: "card-a shareholder", exact: true })).toBeChecked();
    await expect(page.getByRole("checkbox", { name: "card-b shareholder", exact: true })).not.toBeChecked();
    await enter("card-own");
    await expect(page.getByRole("checkbox", { name: "card-b shareholder", exact: true })).toBeChecked();
    await expect(page.getByRole("checkbox", { name: "card-a shareholder", exact: true })).not.toBeChecked();
    await page.screenshot({ path: ".local/shareholder-ballot-verification/own-card.png", fullPage: true });
    await page.getByLabel("Shareholder ID on voting card", { exact: true }).fill("card-external");
    await expect(page.locator(".error-notice")).toContainText("not registered attending");
    await expect(page.getByRole("checkbox", { name: "card-own shareholder", exact: true })).toBeDisabled();
    await page.goto(`${origin}/meetings/${meeting.id}/reports/voting`);
    await page.getByLabel("Attendance type", { exact: true }).selectOption("represented");
    await page.getByRole("button", { name: "Apply filters", exact: true }).click();
    await expect(page.getByRole("cell", { name: "card-ext-a shareholder card-ext-a", exact: true })).toBeVisible();
    const downloadPromise = page.waitForEvent("download");
    await page.getByRole("button", { name: /Export Excel/ }).click();
    const download = await downloadPromise;
    const workbook = XLSX.read(await readFile(await download.path()), { type: "buffer" });
    const exported = XLSX.utils.sheet_to_json(workbook.Sheets["Vote audit"]);
    assert.equal(exported.length, 4);
    assert.ok(exported.every((row) => row["Attendance type"] === "represented" && row["Representative ID"]));
    assert.equal(exported.find((row) => row["Shareholder / historical ballot ID"] === "card-b")["Weight"], 70.5);
    check("browser switches between represented and own cards without sharing choices; representative IDs are rejected; Excel keeps shareholder ownership and representation metadata");

    await db.vote.create({ data: { meetingId: meeting.id, voterId: rep.id, nomineeId: choices[0], weight: 1119.5, snapshotVoterName: rep.name, snapshotVoterShareValue: 1119.5 } });
    assert.equal((await lookup("card-b")).correctionRequired, true);
    await admin.call(`${prefix}/close`, "POST", undefined, 409);
    await admin.call(`${prefix}/votes/close`, "PATCH", undefined, 409);
    await post("card-b", [choices[1]], 409);
    await admin.call(`${prefix}/attendance`, "POST", { shareholderIds: ["card-late"], representativeId: rep.id }, 409);
    await reverse("card-b", [choices[1]]);
    const b = await db.attendance.findFirstOrThrow({ where: { meetingId: meeting.id, shareholderId: "card-b" } });
    await admin.call(`${prefix}/attendance/${b.id}`, "DELETE", undefined, 409);
    const legacyReport = await admin.call(`${prefix}/reports/voting?voterKind=legacy`);
    assert.ok(legacyReport.rows.some((row) => row.voterId === rep.id && row.legacyCombined));
    await page.goto(`${origin}/meetings/${meeting.id}/vote`);
    await page.getByLabel("Shareholder ID on voting card", { exact: true }).fill("card-b");
    await expect(page.getByRole("region", { name: "Older combined ballots" })).toBeVisible();
    await page.getByRole("button", { name: "Reverse older combined vote for card-own shareholder", exact: true }).click();
    await page.getByLabel("Reason for reversal").fill("Replace combined ballot using original shareholder cards");
    await page.getByRole("button", { name: "Reverse choice", exact: true }).click();
    await expect(page.getByRole("region", { name: "Older combined ballots" })).toHaveCount(0);
    await expect(page.getByRole("status").filter({ hasText: "choices used" })).toContainText("70.5 shares");
    await page.getByRole("checkbox", { name: "card-a shareholder", exact: true }).check();
    await page.getByRole("button", { name: "Record 1 choice", exact: true }).click();
    await expect(page.getByRole("button", { name: "Reverse recorded vote for card-a shareholder", exact: true })).toBeVisible();
    await reverse("card-own", [choices[2]]);
    await db.vote.create({ data: { meetingId: meeting.id, voterId: "card-own", nomineeId: choices[2], weight: 1119.5, snapshotVoterName: rep.name, snapshotVoterShareValue: 1119.5 } });
    await post("card-b", [choices[1]], 409);
    assert.equal((await lookup("card-b")).legacyBallots[0].voterId, "card-own");
    await reverse("card-own", [choices[2]]);
    await post("card-own", [choices[2]]);
    check("legacy representative-ID and combined shareholder-ID records block double counting and attendance changes; browser correction requires explicit reversal and original separate cards");
  } finally { await browser.close(); }

  const grouped = (await admin.call("/api/meetings", "POST", { title: "Independent grouped shareholder cards", date: "2026-11-11T09:00:00Z", location: "Test Hall", quorum: 1, firstPassers: 1, secondPassers: 1 }, 201)).item;
  const gp = `/api/meetings/${grouped.id}`;
  const gn = [];
  for (const [index, shareholderId] of ["card-own", "card-a", "card-b"].entries()) gn.push((await admin.call(`${gp}/nominees`, "POST", { shareholderId, type: index < 2 ? "first" : "second" }, 201)).nominee.id);
  await admin.call(`${gp}/open`, "POST");
  await admin.call(`${gp}/attendance`, "POST", { shareholderIds: ["card-a", "card-b"], representativeShareholderId: "card-own" });
  await admin.call(`${gp}/attendance`, "POST", { shareholderIds: ["card-own"], representativeId: "card-external" });
  await admin.call(`${gp}/votingopen`, "POST");
  await admin.call(`${gp}/votes`, "POST", { voterId: "card-a", nomineeIds: [gn[0], gn[2]] });
  await admin.call(`${gp}/votes`, "POST", { voterId: "card-b", nomineeIds: [gn[1], gn[2]] });
  await admin.call(`${gp}/votes`, "POST", { voterId: "card-a", nomineeIds: [gn[1]] }, 400);
  await admin.call(`${gp}/votes`, "POST", { voterId: "card-own", nomineeIds: [gn[1]] });
  const gv = await db.vote.findMany({ where: { meetingId: grouped.id } });
  assert.equal(gv.length, 5);
  assert.equal(gv.filter((vote) => vote.voterId === "card-own")[0].weight, 50);
  assert.equal(gv.filter((vote) => vote.nomineeId === gn[2]).reduce((sum, vote) => sum + vote.weight, 0), 999 + 70.5);
  await admin.call(`${gp}/close`, "POST");
  await admin.call(`${gp}/votes`, "POST", { voterId: "card-b", nomineeIds: [gn[0]] }, 400);
  await admin.call(`${gp}/votes`, "DELETE", { voterId: "card-b", nomineeIds: [gn[2]], reason: "Closed ballot correction blocked" }, 400);
  const ga = await db.attendance.findFirstOrThrow({ where: { meetingId: grouped.id, shareholderId: "card-own" } });
  await admin.call(`${gp}/attendance/${ga.id}`, "DELETE", undefined, 400);
  assert.equal(await db.vote.count({ where: { meetingId: grouped.id } }), 5);
  check("group limits apply independently to each represented card, including a representative who is themselves represented; closed meetings protect every card");
}
